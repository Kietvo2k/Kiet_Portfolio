const root = document.documentElement;
const langButtons = document.querySelectorAll("[data-lang-target]");
const themeToggle = document.querySelector("#themeToggle");
const themeIcon = document.querySelector("#themeIcon");
const metaDescription = document.querySelector('meta[name="description"]');
const metaThemeColor = document.querySelector('meta[name="theme-color"]');

function setLanguage(lang) {
  const nextLang = translations[lang] ? lang : "vi";
  root.dataset.lang = nextLang;
  root.lang = nextLang;
  localStorage.setItem("vtk-lang", nextLang);

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    const value = translations[nextLang][key];
    if (value) {
      element.textContent = value;
    }
  });

  langButtons.forEach((button) => {
    const isActive = button.dataset.langTarget === nextLang;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  document.title = nextLang === "vi" ? "Võ Tuấn Kiệt | Học sinh xây sản phẩm AI" : "Võ Tuấn Kiệt | Student AI Product Builder";
  if (metaDescription) {
    metaDescription.setAttribute(
      "content",
      nextLang === "vi"
        ? "Portfolio song ngữ của Võ Tuấn Kiệt, học sinh cấp 3 theo hướng AI, lập trình và xây dựng sản phẩm số."
        : "Bilingual portfolio of Võ Tuấn Kiệt, a high school student pursuing AI, coding, and digital product building."
    );
  }
  setTheme(root.dataset.theme || "light");
}

function setTheme(theme) {
  const nextTheme = theme === "dark" ? "dark" : "light";
  const lang = translations[root.dataset.lang] ? root.dataset.lang : "vi";
  const copy = translations[lang];
  root.dataset.theme = nextTheme;
  localStorage.setItem("vtk-theme", nextTheme);
  if (themeIcon) {
    themeIcon.textContent = nextTheme === "dark" ? copy.themeLight : copy.themeDark;
  }
  if (themeToggle) {
    themeToggle.setAttribute(
      "aria-label",
      nextTheme === "dark" ? copy.themeToLight : copy.themeToDark
    );
  }
  if (metaThemeColor) {
    metaThemeColor.setAttribute("content", nextTheme === "dark" ? "#101411" : "#f7f5ef");
  }
}

langButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.langTarget));
});

if (themeToggle) {
  themeToggle.addEventListener("click", () => {
    setTheme(root.dataset.theme === "dark" ? "light" : "dark");
  });
}

setTheme(root.dataset.theme || "light");
setLanguage(root.dataset.lang || "vi");

const revealTargets = document.querySelectorAll(
  ".section-header, .story-card, .principle-card, .project-card, .skill-card, .achievement-summary, .achievement-list article, .timeline article, .contact-card"
);

revealTargets.forEach((element, index) => {
  element.classList.add("reveal");
  element.style.setProperty("--reveal-delay", `${Math.min(index % 5, 4) * 70}ms`);
});

if ("IntersectionObserver" in window) {
  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-visible");
          observer.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.16 }
  );

  revealTargets.forEach((element) => observer.observe(element));
} else {
  revealTargets.forEach((element) => element.classList.add("is-visible"));
}
